import fs from "node:fs"
import path from "node:path"
import postcss from "postcss"

const uiDir = path.resolve("web/src/ui")
const files = fs.readdirSync(uiDir).filter(name => name.endsWith(".css")).sort()
const marker = "/* UI priority layers: generated by scripts/consolidate-ui-priority.mjs */"

function appendClone(target, node) {
  target.push(node.clone())
}

function splitRule(rule, base, priority) {
  const baseRule = rule.clone({ nodes: [] })
  const priorityRule = rule.clone({ nodes: [] })
  for (const child of rule.nodes || []) {
    if (child.type === "decl" && child.important) {
      const declaration = child.clone()
      declaration.important = false
      priorityRule.append(declaration)
    } else {
      baseRule.append(child.clone())
    }
  }
  if (baseRule.nodes?.length) base.push(baseRule)
  if (priorityRule.nodes?.length) priority.push(priorityRule)
}

function splitAtRule(rule, base, priority) {
  if (!rule.nodes || ["keyframes", "-webkit-keyframes", "font-face"].includes(rule.name)) {
    appendClone(base, rule)
    return
  }
  const baseChildren = []
  const priorityChildren = []
  splitNodes(rule.nodes, baseChildren, priorityChildren)
  if (baseChildren.length) {
    const clone = rule.clone({ nodes: [] })
    clone.append(baseChildren)
    base.push(clone)
  }
  if (priorityChildren.length) {
    const clone = rule.clone({ nodes: [] })
    clone.append(priorityChildren)
    priority.push(clone)
  }
}

function splitNodes(nodes, base, priority) {
  for (const node of nodes) {
    if (node.type === "rule") splitRule(node, base, priority)
    else if (node.type === "atrule") splitAtRule(node, base, priority)
    else appendClone(base, node)
  }
}

for (const file of files) {
  const target = path.join(uiDir, file)
  const source = fs.readFileSync(target, "utf8")
  if (source.startsWith(marker)) continue
  const root = postcss.parse(source, { from: target })
  const baseNodes = []
  const priorityNodes = []
  splitNodes(root.nodes, baseNodes, priorityNodes)
  const output = postcss.root()
  output.append(postcss.comment({ text: "UI priority layers: generated by scripts/consolidate-ui-priority.mjs" }))
  if (file === "tokens.css") output.append(postcss.atRule({ name: "layer", params: "mn-ui-base, mn-ui-priority" }))
  const baseLayer = postcss.atRule({ name: "layer", params: "mn-ui-base" })
  baseLayer.append(baseNodes)
  output.append(baseLayer)
  if (priorityNodes.length) {
    const priorityLayer = postcss.atRule({ name: "layer", params: "mn-ui-priority" })
    priorityLayer.append(priorityNodes)
    output.append(priorityLayer)
  }
  fs.writeFileSync(target, output.toString())
}

console.log(`Converted ${files.length} UI modules from declaration-level !important to two explicit cascade layers.`)
